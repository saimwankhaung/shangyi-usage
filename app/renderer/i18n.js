function text(locale, key) { return (translations[locale] || translations.en)[key] || translations.en[key] || key; }
function localizeMessage(locale, message) { return locale === 'th' ? thaiMessages[message] || message : message; }
function quotaLabel(row, locale) {
  if (locale === 'my') { if (row.windowMinutes === 300 || row.id === 'five_hour') return '၅ နာရီအတွက် limit'; if (row.windowMinutes === 10080 || row.id === 'seven_day') return 'တစ်ပတ်အတွက် limit'; }
  if (locale === 'th') {
    const minutes = row.windowMinutes || (row.id === 'five_hour' ? 300 : row.id === 'seven_day' ? 10080 : null);
    if (minutes > 0) return 'ขีดจำกัด ' + (minutes % 1440 === 0 ? minutes / 1440 + ' วัน' : minutes % 60 === 0 ? minutes / 60 + ' ชั่วโมง' : minutes + ' นาที');
    return { 'Session limit': 'ขีดจำกัดรอบการใช้งาน', 'Weekly limit': 'ขีดจำกัดรายสัปดาห์', 'Spend limit': 'ขีดจำกัดค่าใช้จ่าย' }[row.label] || row.label;
  }
  return row.label;
}
const burmeseDigits = value => String(value).replace(/[0-9]/g, digit => '၀၁၂၃၄၅၆၇၈၉'[digit]);
function countdown(seconds, locale) {
  const total = Math.max(0, Math.ceil(seconds / 60)), days = Math.floor(total / 1440), hours = Math.floor(total / 60) % 24, minutes = total % 60;
  if (locale === 'th') return days ? days + ' วัน ' + hours + ' ชม.' : hours ? hours + ' ชม. ' + minutes + ' นาที' : minutes + ' นาที';
  if (locale === 'my') return burmeseDigits(days ? days + ' ရက် ' + hours + ' နာရီ' : hours ? hours + ' နာရီ ' + minutes + ' မိနစ်' : minutes + ' မိနစ်');
  return days ? days + 'd ' + hours + 'h' : hours ? hours + 'h ' + minutes + 'm' : minutes + 'm';
}
function age(timestamp, locale, now = Date.now()) {
  if (!timestamp) return '—';
  const seconds = Math.max(0, Math.floor((now - timestamp) / 1000));
  if (locale === 'my') return burmeseDigits(seconds < 60 ? seconds + ' စက္ကန့်အကြာက' : seconds < 3600 ? Math.floor(seconds / 60) + ' မိနစ်အကြာက' : Math.floor(seconds / 3600) + ' နာရီအကြာက');
  if (locale === 'th') return seconds < 60 ? seconds + ' วินาทีที่แล้ว' : seconds < 3600 ? Math.floor(seconds / 60) + ' นาทีที่แล้ว' : Math.floor(seconds / 3600) + ' ชั่วโมงที่แล้ว';
  return seconds < 60 ? seconds + 's ago' : seconds < 3600 ? Math.floor(seconds / 60) + 'm ago' : Math.floor(seconds / 3600) + 'h ago';
}
